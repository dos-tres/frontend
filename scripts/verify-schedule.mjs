import assert from 'node:assert/strict'
import {build} from 'esbuild'
const built=await build({entryPoints:['src/schedule.ts'],bundle:true,write:false,format:'esm',platform:'node'})
const m=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'))
const now=new Date(2026,10,21,12)
assert.deepEqual(m.parseSchedule('내일 오후 3시부터 4시 상담 등록해줘',now),{date:'2026-11-22',startTime:'15:00',endTime:'16:00',title:'상담'})
assert.equal(m.parseSchedule('다음주 월요일 오전 10시 반 상담',now).date,'2026-11-23')
assert.equal(m.parseSchedule('오전 12시',now).startTime,'00:00')
assert.equal(m.parseSchedule('오후 12시',now).startTime,'12:00')
assert.equal(m.parseSchedule('3시',now).startTime,undefined)
assert.equal(m.parseSchedule('15:30',now).startTime,'15:30')
assert.equal(m.parseSchedule('내일 오후 3시 상담 1시간 전에 알려줘',now).reminderMinutes,60)
assert.equal(m.parseSchedule('내일 오후 3시 상담 1시간 전에 알려줘',now).endTime,undefined)
const e={id:1,title:'상담',date:'2026-11-22',type:'개인 일정',startTime:'15:00',endTime:'16:00',reminderMinutes:10}
assert.equal(m.validateEvent(e),'')
for(const patch of [{date:'2026-02-30'},{startTime:'25:00'},{endTime:'14:00'},{title:''}])assert.ok(m.validateEvent({...e,...patch}))
const at=new Date('2026-11-22T14:50:00').getTime()
assert.equal(m.dueReminders([e],at).length,1)
assert.equal(m.dueReminders([{...e,notifiedAt:'done'}],at).length,0)
assert.equal(m.dueReminders([e],at-1).length,0)
assert.equal(m.dueReminders([e],at+3600000).length,0)
assert.equal(m.dueReminders([{...e,startTime:undefined}],at).length,0)
const blocks=m.timeBlocks([e,{...e,id:2,startTime:'15:30',endTime:'16:30'},{...e,id:3,startTime:'16:30',endTime:'17:00'}])
assert.deepEqual(blocks.map(b=>b.lane),[0,1,0])
assert.equal(blocks[0].end-blocks[0].start,60)
console.log('PASS: relative dates, AM/PM, missing time, invalid dates/ranges, one-time due reminders, overlapping time blocks')

const korean=m.parseSchedule('11월 24일 오전 11시에 준비물 문의 일정 등록해줘',new Date(2026,10,22))
assert.deepEqual(korean,{date:'2026-11-24',startTime:'11:00',title:'준비물 문의'})
console.log('PASS: Korean month/day date and time particles')
